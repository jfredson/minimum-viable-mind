def bootstrap_raw(w_hits, o_hits, seed, n=1000) -> dict:
    """The within-seed bootstrap over matched pairs of the raw difference."""
    rng = np.random.default_rng([20261004, seed])
    k = len(w_hits)
    d = [float((w_hits[i] - o_hits[i]).mean()) for i in (rng.integers(0, k, k) for _ in range(n))]
    return dict(resamples=n, sd=float(np.std(d)), p2_5=float(np.percentile(d, 2.5)),
                p97_5=float(np.percentile(d, 97.5)))


def measure_at(m, arm, seed, spec, coefs, data: EvalData, described_only: bool) -> tuple:
    """Everything at one site set, on fresh episodes (the rehearsal's
    `rerun_controls.measure_at`, with control 4 as redefined)."""
    recip, donor = data.fresh
    D = m.cfg.d_model
    d_tgt = donor["targets"][:, G.OWN]
    with torch.no_grad():
        clean = m(recip)
    u_hits = hits(clean, d_tgt, G.OWN)
    u = float(u_hits.mean())
    acc = float(hits(clean, recip["targets"][:, G.OWN], G.OWN).mean())
    d_states = X.capture(m, donor)
    r_states = X.capture(m, recip)
    L = tuple(spec["layers"])
    sites = X.Sites(L, spec["positions"])
    mask = X.position_mask(recip, spec["positions"])
    basis = {l: X.basis_for(coefs[l], spec["rank"]) for l in L}
    w_hits = hits(run(m, recip, d_states, sites, mask, None), d_tgt, G.OWN)
    o_hits = hits(run(m, recip, d_states, sites, mask, basis), d_tgt, G.OWN)
    w, o = float(w_hits.mean()), float(o_hits.mean())
    row = dict(site_set=spec, described_only=described_only,
               reading=MS.reading(w, o, u, acc),
               no_transplant=MS.no_transplant_rule(u, acc),
               bootstrap_raw_difference=bootstrap_raw(w_hits, o_hits, seed))
    c = {}
    # control 1: the complement of the piece; holds on arm T only
    comp = {l: X.complement_basis(basis[l]) for l in L}
    c1 = float(hits(run(m, recip, d_states, sites, mask, comp), d_tgt, G.OWN).mean())
    c["1"] = dict(complement_donor_share=c1, whole=w, untouched=u,
                  holds=(c1 <= u + MS.CONTROL1_ROOM) if arm == "T" else None,
                  holds_on_arm_T_only=True)
    # control 3: twenty random pieces, reported
    rand = [float(hits(run(m, recip, d_states, sites, mask, rb), d_tgt, G.OWN).mean())
            for rb in X.random_bases(spec["rank"], L, seed, D)]
    c["3"] = dict(draws=rand, median=float(np.median(rand)), p95=float(np.percentile(rand, 95)),
                  ownership_only=o, below=sum(x < o for x in rand),
                  equal=sum(x == o for x in rand), above=sum(x > o for x in rand))
    # control 4, as redefined: before both twins' first own turns; holds if bit-identical
    pre = X.before_both_twins(recip, donor)
    moved4 = run(m, recip, d_states, sites, pre, None)
    c["4"] = dict(holds=bool(torch.equal(clean, moved4)),
                  largest_output_difference=float((clean - moved4).abs().max()),
                  donor_value_share=float(hits(moved4, d_tgt, G.OWN).mean()),
                  no_transplant_share=u,
                  trials_whose_action_changed=int((X.predictions(moved4, G.OWN)
                                                   != X.predictions(clean, G.OWN)).sum()),
                  twins_states_identical_at_the_sites=all(
                      bool(torch.equal(d_states[l][pre], r_states[l][pre])) for l in L))
    # control 6: same value against different value, on the relaxed set
    cr, cd = data.relaxed
    cs = X.capture(m, cd)
    ct = cd["targets"][:, G.OWN]
    cm = X.position_mask(cr, spec["positions"])
    same = (cr["targets"][:, G.OWN] == ct)
    with torch.no_grad():
        c_clean = X.predictions(m(cr), G.OWN)
    moved = X.predictions(run(m, cr, cs, sites, cm, None), G.OWN) != c_clean
    c["6"] = dict(same_value_trials=int(same.sum()), different_value_trials=int((~same).sum()),
                  same_value_moved=float(moved[same].float().mean()) if int(same.sum()) else None,
                  different_value_moved=float(moved[~same].float().mean()))
    # control 7: the null transplant; holds if bit-identical
    nullout = run(m, recip, r_states, sites, mask, None)
    c["7"] = dict(holds=bool(torch.equal(clean, nullout)))
    row["controls"] = c
    if arm in ("T", "M"):
        eye = torch.eye(D)[:, m.cfg.d_content:]
        oh = float(hits(run(m, recip, d_states, sites, mask, {l: eye for l in L}), d_tgt, G.OWN).mean())
        row["true_slot"] = dict(reading=MS.reading(w, oh, u, acc))
    if arm == "M":
        route = m.entangled_route(recip)[:, G.OWN].numpy()
        aT, uT = float(w_hits[~route].mean()), float(u_hits[~route].mean())
        aC, uC = float(w_hits[route].mean()), float(u_hits[route].mean())
        p = float(route.mean())
        row["true_slot"]["route_formula"] = p * (aC - uC) / ((1 - p) * (aT - uT) + p * (aC - uC))
        row["true_slot"]["entangled_share"] = p
    return row, dict(recip=recip, d_states=d_states, d_tgt=d_tgt, u=u, acc=acc)


def control2(m, arm, seed, reads, data: EvalData, other_correct, gate_bar, family, piece_min):
    """Control 2, the other-agent control: a reported description beside
    twenty random pieces, no pass line (ruled 2026-10-03, ruling 1; the twenty
    by ruling 5 of the late evening; this function by the ruling of
    2026-10-04, item 4). The rehearsal's `control2_twenty_draws.control2`."""
    if arm in ("T", "M"):
        return dict(status="not applicable", reason="ruled: the named agent is held outside the running state")
    if other_correct < gate_bar:
        return dict(status="no verdict", named_other_correct=other_correct,
                    reason="the arm has not learned the named-other condition")
    coefs = reads["named"]
    dev, _ = data.dev
    fits = accuracies(m, dev, coefs, "named", G.OTHER)
    g = grid(m, dev, data.dev_swap, coefs, G.OTHER, family)
    best, why, cands = pick(g["grid"], fits, family, piece_min)
    out = dict(named_other_correct=other_correct, named_read_fits=fits,
               dev_untouched=g["untouched"], dev_named_other_accuracy=g["arm_accuracy"],
               candidates=[spec_of(c) | dict(dev_ownership_only=c["accuracy_ownership_only"],
                                             dev_whole=c["accuracy_whole"]) for c in cands])
    if best is None:
        out.update(status="no verdict", reason=why)
        return out
    spec = spec_of(best)
    fr = data.fresh[0]
    L = tuple(spec["layers"])
    sites = X.Sites(L, spec["positions"])
    mask = X.anchored_mask(fr, spec["positions"], G.OTHER)
    basis = {l: X.basis_for(coefs[l], spec["rank"]) for l in L}
    s_states = X.capture(m, data.fresh_swap)
    with torch.no_grad():
        clean = m(fr)
    own_clean, oth_clean = X.predictions(clean, G.OWN), X.predictions(clean, G.OTHER)

    def moved(bb, cond, base):
        return float((X.predictions(run(m, fr, s_states, sites, mask, bb), cond) != base).float().mean())

    own_moved = moved(basis, G.OWN, own_clean)
    draws = [moved(rb, G.OWN, own_clean) for rb in X.random_bases(spec["rank"], L, seed, m.cfg.d_model)]
    out.update(status="reported; no pass line", site_set=spec, trials=int(own_clean.shape[0]),
               own_directed_moved=own_moved,
               random_pieces=dict(draws=len(draws), own_directed_moved=draws,
                                  median=float(np.median(draws)), p95=float(np.percentile(draws, 95)),
                                  below=sum(x < own_moved for x in draws),
                                  equal=sum(x == own_moved for x in draws),
                                  above=sum(x > own_moved for x in draws)),
               named_other_moved=moved(basis, G.OTHER, oth_clean))
    return out


# ------------------------------------------------------------ one model

def load_model(ckpt: str, arm: str | None, size: str | None):
    obj = torch.load(ckpt, map_location=DEVICE, weights_only=True)
    if isinstance(obj, dict) and "state" in obj and "cfg" in obj:
        m = M.build_from_config(obj["cfg"])
        m.load_state_dict(obj["state"], strict=True)
        meta = dict(cfg=obj["cfg"], step=obj.get("step"), tokens_seen=obj.get("tokens_seen"))
    else:
        if not (arm and size):
            raise SystemExit("a bare state dictionary needs --arm and --size")
        m = M.build(arm, size)
        m.load_state_dict(obj, strict=True)
        meta = dict(cfg=M.config_dict(m))
    return m.eval(), meta


def sha256(path):
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def run_model(ckpt, out_dir, arm=None, size=None, seed=None, reads_npz=None,
              shuffles=MS.N_SHUFFLES, scale=1.0, piece_rule_off_for_control2=False,
              data: EvalData | None = None) -> dict:
    """Every step for one trained model. Writes the row and the reads."""
    t0 = time.time()
    torch.set_num_threads(max(1, torch.get_num_threads()))
    m, meta = load_model(ckpt, arm, size)
    arm = m.cfg.arm
    seed = int(seed if seed is not None else 0)
    data = data or EvalData(scale)
    fam, strict = check_family(m.cfg.n_states)
    os.makedirs(out_dir, exist_ok=True)
    row = dict(arm=arm, seed=seed, checkpoint=os.path.abspath(ckpt), checkpoint_sha256=sha256(ckpt),
               model=meta, versions=versions(), episode_scale=scale,
               registered_counts=scale == 1.0,
               family=dict(site_sets=len(fam), comparisons=len(fam) * len(RANKS),
                           stricter_site_sets=len(strict)))
    if scale != 1.0:
        row["NOT_A_REGISTERED_FIGURE"] = "episode counts scaled for a pipeline test"
    # the gate
    row["gate"] = gate(m, arm, data)
    log(f"[{arm}/{seed}] gate: own {row['gate']['own_correct']}, named-other "
        f"{row['gate']['other_correct']} of {row['gate']['episodes']} (bar {row['gate']['bar']})")
    # the reads: fitted once here, or taken from a file (test T3a only)
    dev, dev_donor = data.dev
    if reads_npz:
        reads = load_reads(reads_npz)
        row["reads_source"] = os.path.abspath(reads_npz)
    else:
        reads = fit_reads(m, dev)
        row["reads_source"] = "fitted once by this run, on the processor"
    reads_path = os.path.join(out_dir, f"reads_{arm}_seed{seed}.npz")
    save_reads(reads_path, reads)
    reads = load_reads(reads_path)          # reloaded, never refitted (section 7.1)
    coefs = reads["own"]
    fits = accuracies(m, dev, coefs, "own", G.OWN)
    row["fits"] = {str(l): dict(v, band=MS.sampling_band(v["whole"], data.held_out, data.piece_min))
                   for l, v in fits.items()}
    row["null"] = {str(l): v for l, v in null(m, dev, seed, shuffles).items()} if shuffles else None
    log(f"[{arm}/{seed}] reads: whole-read counts by state "
        f"{[fits[l]['whole'] for l in sorted(fits)]} of {data.held_out}")
    # nomination, on development episodes
    g = grid(m, dev, dev_donor, coefs, G.OWN, fam)
    best, why, cands = pick(g["grid"], fits, fam, data.piece_min)
    sbest, swhy, _ = pick(g["grid"], fits, strict, data.piece_min)
    unfiltered, _, _ = pick(g["grid"], fits, fam, data.piece_min, require_piece=False)
    sens = pick_sensitivity(g["grid"], fits, fam, data.piece_min)
    row["nomination"] = dict(
        dev_untouched=g["untouched"], dev_accuracy=g["arm_accuracy"],
        site_sets_clearing=len({(tuple(x["layers"]), x["positions"]) for x in g["grid"] if x["floor"]["clears"]}),
        candidates=[spec_of(c) | dict(dev_ownership_only=c["accuracy_ownership_only"],
                                      dev_whole=c["accuracy_whole"],
                                      piece_band=MS.sampling_band(c["piece_correct"], data.held_out, data.piece_min))
                    for c in cands],
        primary=dict(status=why, site_set=spec_of(best)),
        stricter=dict(status=swhy, site_set=spec_of(sbest)),
        sensitivity=spec_of(sens),
        piece_rule_switched_off=spec_of(unfiltered))
    row["grid"] = g["grid"]
    log(f"[{arm}/{seed}] nomination: {why} {spec_of(best)}")
    # the reading, on fresh episodes
    spec = spec_of(best)
    described = spec is None
    if described:
        spec = spec_of(unfiltered)
    row["nomination_status"] = why
    if spec is not None:
        dev_floor = next(x["floor"]["clears"] for x in g["grid"]
                         if x["layers"] == spec["layers"] and x["positions"] == spec["positions"])
        prim, ctx = measure_at(m, arm, seed, spec, coefs, data, described)
        prim["dev_floor_clears"] = dev_floor
        prim["piece_elsewhere"] = piece_elsewhere(m, dev, spec, coefs)
        prim["fit_floor"] = MS.sampling_band(spec["piece_correct"], data.held_out, data.piece_min)
        prim["whole_read_at_worst_state"] = spec["whole_read_correct"]
        worst = min(spec["layers"], key=lambda l: (fits[l]["whole"], l))
        if row["null"]:
            prim["null_at_worst_state"] = dict(state=worst, **row["null"][str(worst)])
        row["primary"] = prim
        for name, s in (("stricter", spec_of(sbest)), ("sensitivity", spec_of(sens))):
            if s is not None:
                r2, _ = measure_at(m, arm, seed, s, coefs, data, False)
                row[name] = dict(site_set=s, reading=r2["reading"], no_transplant=r2["no_transplant"],
                                 controls={k: r2["controls"][k] for k in ("1", "4", "7")})
        # the rider: arm T's site set for this seed, this arm's own read
        # (on arm T itself it is its own site set, and equals its reading)
        t_row = os.path.join(out_dir, f"row_T_seed{seed}.json")
        tspec = spec_of(best) if arm == "T" else (
            json.load(open(t_row))["nomination"]["primary"]["site_set"] if os.path.exists(t_row) else None)
        if tspec is not None:
            tL = tuple(tspec["layers"])
            ts = X.Sites(tL, tspec["positions"])
            tm = X.position_mask(ctx["recip"], tspec["positions"])
            tb = {l: X.basis_for(coefs[l], tspec["rank"]) for l in tL}
            tw = float(hits(run(m, ctx["recip"], ctx["d_states"], ts, tm, None), ctx["d_tgt"], G.OWN).mean())
            to = float(hits(run(m, ctx["recip"], ctx["d_states"], ts, tm, tb), ctx["d_tgt"], G.OWN).mean())
            row["rider_at_arm_T_site_set"] = dict(
                site_set=dict(layers=list(tL), positions=tspec["positions"], rank=tspec["rank"]),
                reading=MS.reading(tw, to, ctx["u"], ctx["acc"]))
    # control 2
    c2_min = 0 if piece_rule_off_for_control2 else data.piece_min
    row["control2"] = control2(m, arm, seed, reads, data, row["gate"]["other_correct"],
                               row["gate"]["bar"], fam, c2_min)
    if piece_rule_off_for_control2:
        row["control2"]["NOT_A_RESULT"] = "the piece rule was switched off for control 2 (test T3 only)"
    row["seconds"] = time.time() - t0
    path = os.path.join(out_dir, f"row_{arm}_seed{seed}.json")
    with open(path, "w") as f:
        json.dump(row, f, indent=1, sort_keys=True, default=_json_default)
    p = row.get("primary")
    log(f"[{arm}/{seed}] done in {row['seconds']:.0f}s: "
        + (f"arithmetic {p['reading']['degree']}, controls 7/4 hold {p['controls']['7']['holds']}/"
           f"{p['controls']['4']['holds']}" if p else "no site set") + f" -> {path}")
    return row


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, (set, tuple)):
        return list(o)
    raise TypeError(type(o))


# ------------------------------------------------------------ summarise

def summarise(out_dir: str, gates_after_rerun: dict | None = None) -> dict:
    """Every row in `out_dir` to the registered outcome, under the rulings of
    2026-10-06. Each seed is judged on its own gate conditions and every
    withholding check (page 7: `measure.withhold`); an arm passes its
    learning gate if two seeds each pass every learning condition, and reads
    if two seeds count. Arm F's step 5a run is named in `steps.json` beside
    the rows (`{"arm_F_step_5a_seed": s}`), if there is one. Nothing a
    withheld seed computed is written to `summary.json` or `table.md`."""
    rows = {}
    for f in sorted(os.listdir(out_dir)):
        if f.startswith("row_") and f.endswith(".json"):
            r = json.load(open(os.path.join(out_dir, f)))
            rows[(r["arm"], r["seed"])] = r
    steps_path = os.path.join(out_dir, "steps.json")
    steps = json.load(open(steps_path)) if os.path.exists(steps_path) else {}
    arms_present = sorted({a for a, _ in rows}, key=M.ARMS.index)
    gates, verdicts, per_seed = {}, {}, {}
    for arm in arms_present:
        seeds = sorted(s for a, s in rows if a == arm)
        per_seed[arm] = {}
        for s in seeds:
            r = rows[(arm, s)]
            p = r.get("primary") or {}
            w_in = dict(gate=r.get("gate"), nomination_status=r.get("nomination_status"),
                        reading=p.get("reading"), controls=p.get("controls"))
            for k in ("described_only", "dev_floor_clears"):
                if k in p:
                    w_in[k] = p[k]
            per_seed[arm][s] = MS.withhold(w_in, arm)
        verdicts[arm] = MS.arm_outcome(per_seed[arm])
        gates[arm] = verdicts[arm]["gate_passes"]
        if gates_after_rerun and arm in gates_after_rerun:
            gates[arm] = gates_after_rerun[arm]
    step_5a = None
    if "arm_F_step_5a_seed" in steps:
        s5 = int(steps["arm_F_step_5a_seed"])
        w = per_seed.get("F", {}).get(s5)
        step_5a = dict(seed=s5, passed=bool(w and w["learning_passes"]),
                       failed_conditions=[MS._GATE_REASON[k] for k, v in ((w or {}).get("checks") or {}).items()
                                          if k.endswith("learning") and v != MS.PASSED])
    true_slot = {s: rows[("M", s)]["primary"]["true_slot"]["reading"]["degree"]
                 for a, s in rows if a == "M" and (rows[(a, s)].get("primary") or {}).get("true_slot")}
    res = dict(per_seed=per_seed, arms=verdicts, gates=gates, steps=steps)
    res["outcome"] = MS.outcome(gates, verdicts, true_slot, step_5a)
    # reported, never a veto (page 8)
    res["no_transplant_reported"] = {
        f"{a}/{s}": rows[(a, s)]["primary"]["no_transplant"]
        for (a, s) in rows if (rows[(a, s)].get("primary") or {}).get("no_transplant")
        and per_seed[a][s]["status"] == "reading"}
    raw = {a: [rows[(a, s)]["primary"]["reading"]["raw_difference"] for s in sorted(per_seed[a])
               if per_seed[a][s]["status"] == "reading"] for a in arms_present}
    res["across_seed_spread_of_raw_difference"] = {a: (float(np.std(v, ddof=1)) if len(v) > 1 else None)
                                                    for a, v in raw.items()}
    res["versions"] = versions()
    with open(os.path.join(out_dir, "summary.json"), "w") as f:
        json.dump(res, f, indent=1, sort_keys=True, default=_json_default)
    with open(os.path.join(out_dir, "table.md"), "w") as f:
        f.write(table(rows, per_seed, res) + "\n")
    return res


def _deg(x) -> str:
    """A reading or share as printed: four places, or "no verdict" when the
    arithmetic was not made (an untrained model's true-slot reference, for
    one; the toy never produced one, the 30M pipeline test did)."""
    return "no verdict" if x is None else f"{x:.4f}"


def table(rows, per_seed, res) -> str:
    def site(s):
        return "" if s is None else f"states {tuple(s['layers'])} at {s['positions']}, {s['rank']} directions"
    out = ["| arm/seed | reading or no verdict | site set | whole read / piece of the held-out count (band) | "
           "piece elsewhere: per position; average | whole, ownership-only, untouched (fresh) | "
           "no-transplant miss | control 3 median, 95th; below/equal/above | controls 7, 1 (arm T), 4 hold | "
           "control 6 same / different moved | control 2 | true slot | rider | lesion own | lesion candidates |",
           "|" + "---|" * 15]
    for (arm, s), r in sorted(rows.items(), key=lambda kv: (M.ARMS.index(kv[0][0]), kv[0][1])):
        w = per_seed[arm][s]
        verdict = (f"{w['degree']:.4f}" if w["status"] == "reading"
                   else "no verdict: " + "; ".join(w["reasons"]))
        p = r.get("primary")
        lc = r["gate"].get("lesioned_candidate_own_correct", "not run")
        if not p or w["status"] != "reading":
            # a withheld seed: nothing computed from its reading is printed (A2, item 7)
            out.append(f"| {arm}/{s} | {verdict} |" + " withheld |" * 12
                       + f" {r['gate']['lesioned_own_correct']} | {lc} |")
            continue
        sp, rd, c = p["site_set"], p["reading"], p["controls"]
        b = p["fit_floor"]
        pe = p["piece_elsewhere"]
        elsewhere = ("single position" if not pe["other_positions"] else
                     ", ".join(str(e["piece"]) for e in pe["other_positions"])
                     + f"; {pe['mean_over_the_other_positions']['piece']}")
        ts = p.get("true_slot")
        rider = r.get("rider_at_arm_T_site_set")
        c2 = r["control2"]
        out.append(
            f"| {arm}/{s} | {verdict} | {site(sp)} | {sp['whole_read_correct']} / {sp['piece_correct']} "
            f"({b['interval_95'][0]} to {b['interval_95'][1]}) | {elsewhere} | "
            f"{rd['accuracy_whole']:.4f}, {rd['accuracy_ownership_only']:.4f}, {rd['accuracy_untouched']:.4f} | "
            f"{p['no_transplant']['miss']:+.4f} | {c['3']['median']:.4f}, {c['3']['p95']:.4f}; "
            f"{c['3']['below']}/{c['3']['equal']}/{c['3']['above']} | {c['7']['holds']}, {c['1']['holds']}, {c['4']['holds']} | "
            f"{_deg(c['6']['same_value_moved'])} / {_deg(c['6']['different_value_moved'])} | {c2['status']} | "
            f"{'' if not ts else _deg(ts['reading']['degree'])} | "
            f"{'' if not rider else _deg(rider['reading']['degree'])} | {r['gate']['lesioned_own_correct']} | {lc} |")
    o = res.get("outcome")
    out += ["", f"outcome: {o['term'] if o and o.get('code') else 'not computed: ' + str(o and o.get('reason'))}"]
    if o and o.get("sentence"):
        out.append(f"as reported: {o['sentence']}")
    if o and o.get("separation"):
        sp = o["separation"]
        out.append("separation (arm C lowest minus arm T highest): "
                   + (f"{sp['value']:.4f} against {sp['bar']}" if sp.get("computed") else sp.get("reason", "")))
    if o and o.get("notes"):
        out += [f"note: {n}" for n in o["notes"]]
    return "\n".join(out)


def self_test() -> None:
    """Test T4: the site-set rule at three depths, and the band and family
    numbers the reporting table prints."""
    fails = []

    def check(name, ok, detail=""):
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  {detail}" if detail else ""))
        if not ok:
            fails.append(name)

    print("procedure.py self-test: the site-set rule")
    for n_states, size in ((5, "toy"), (9, "10M"), (13, "30M")):
        fam, strict = site_family(n_states), site_family(n_states, strict=True)
        assert M.build("F", size).cfg.n_states == n_states
        spans_all = [x for x in fam if x[1] == "all"]
        l0 = [x for x in fam if 0 in x[0] and x[1] != "action"]
        check(f"{size} ({n_states} running states): {len(fam)} site sets, {len(fam) * len(RANKS)} "
              f"comparisons; stricter {len(strict)}; none spans every position; layer 0 at `action` only",
              not spans_all and not l0 and len(set(fam)) == len(fam)
              and (n_states not in EXPECTED_FAMILY or (len(fam), len(strict)) == EXPECTED_FAMILY[n_states]))
    check("the registered model's list is version 4's section 18: 325 site sets, 1,300 comparisons; "
          "stricter 312", check_family(13) and len(site_family(13)) * 4 == 1300)
    fam13 = site_family(13)
    first_rows = [sum(1 for L, P in fam13 if L[0] == a) for a in range(13)]
    check("row by row as section 18 prints it (13, 48, 44, ... 4)",
          first_rows == [13, 48, 44, 40, 36, 32, 28, 24, 20, 16, 12, 8, 4], str(first_rows))
    check("the gate bar on 3,000 episodes is 790 by the one-sided binomial rule",
          binomial_bar(3000) == 790)
    eps = G.episodes_from_pairs(G.eval_pairs("gate"))
    cand = candidate_ids(eps)
    tgt = np.stack([e["targets"] for e in eps])
    check("ownership-free line: four distinct candidates per answer on every gate episode, the right "
          "answer always among them (page 1, RT-237)",
          all(len(set(cand[i, c])) == 4 and tgt[i, c] in cand[i, c] for i in range(len(eps)) for c in (0, 1)))
    check("ownership-free line: answering the right value counts as a candidate, a non-value word does not",
          candidate_count(tgt, cand, G.OWN) == len(eps)
          and candidate_count(np.zeros_like(tgt), cand, G.OWN) == 0)
    torch.manual_seed(0)
    g = gate(M.build("F", "toy"), "F", EvalData(scale=0.02))
    check("the gate writes the lesioned candidate count and its line for every arm and seed (RT-237, change 5)",
          {"lesioned_candidate_own_correct", "lesioned_candidate_other_correct", "ownership_free_line"} <= set(g)
          and g["ownership_free_line"] == MS.ownership_free_line(g["episodes"]),
          f"{g['lesioned_candidate_own_correct']} of {g['episodes']}, line {g['ownership_free_line']}")
    check("the table prints a reading that was not made as 'no verdict' instead of failing",
          _deg(None) == "no verdict" and _deg(0.48859) == "0.4886")
    print(f"\n{len(fails)} failure(s)" if fails else "\nall checks passed")
    if fails:
        raise SystemExit(1)


