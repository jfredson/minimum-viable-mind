"""The measurement procedure: from a trained model to a row of the reporting
table, and from twelve rows to the registered outcome.

FROZEN CODE, NOT YET REGISTERED. Frozen 2026-10-04 under
`docs/successor-code-freeze-method-2026-10-04.md`. It implements sections 7
and 8 of `docs/successor-experiment-proposal-2026-10-03-v4.md`.

Where it comes from
-------------------
Every toy figure version 4 quotes was produced by four rehearsal scripts in
`experiments/rehearsal-successor-measure/src/`, each built on the one before:
`rerun_controls.py` (nomination, the reading, controls 1, 3, 6 and 7, the
rider, the true-slot reference), `short_prestated_run.py` (control 4 as
redefined, and the piece's accuracy at the other positions of its site, both
ways), `control2_twenty_draws.py` (control 2 beside twenty random pieces, the
registered control 2 by the ruling of 2026-10-04, item 4) and `rerun_v3.py`
(the gate and the 200-shuffle null). This file brings them into one procedure
with the arithmetic of each step unchanged, and adds what version 4 says the
registered code must do that the toy code did not:

- the site-set family is generated by the rule for whatever depth the model
  has, and its size asserted (325 site sets on the registered model);
- the straight-line reads are fitted once, on the laptop's processor, written
  to disk, and the printed counts and the transplanted directions both come
  from that one fit (section 7.2, item 1);
- the sampling band is printed beside every count against the floor;
- a reading is withheld, in the output, when a control that holds fails, the
  no-transplant rate is outside its allowance, or the floor is missed on fresh
  episodes (`measure.withhold`);
- an arm's three seeds become a reading by two of three, and the separation
  is arm C's lowest minus arm T's highest (`measure.arm_outcome`,
  `measure.separation`, `measure.outcome`);
- the within-seed bootstrap over matched pairs is printed beside the
  across-seed spread (section 9, row "uncertainty across seeds").

How it is run
-------------
    python procedure.py model --ckpt PATH --out DIR [--arm A --size toy --seed S]
    python procedure.py summarise --dir DIR

`model` runs every step for one trained model and writes
`row_{arm}_seed{seed}.json` and `reads_{arm}_seed{seed}.npz` into DIR. Run
arm T's three seeds first: the rider for the other arms reads arm T's site set
for the same seed from DIR. `summarise` reads every row in DIR and writes
`summary.json` and `table.md`, with the outcome term.

Everything runs on the processor (ruled 2026-10-03, ruling 3). Library
versions are written into every output and pinned in
`../requirements-measure.txt`.

Corrigibility: local, inference and small logistic regressions only, no
network, no rented machine, $0 [C1/C2].
"""
