def site_family(n_states: int, strict: bool = False) -> list:
    """Section 7.2, item 2: every contiguous set of running states at the four
    position sets; layer 0 kept at `action` only; the stricter variant removes
    layer 0 everywhere. No set spans every position."""
    contig = [tuple(range(a, b + 1)) for a in range(n_states) for b in range(a, n_states)]
    fam = [(L, P) for L in contig for P in POS if not (0 in L and P != "action")]
    if strict:
        fam = [(L, P) for (L, P) in fam if 0 not in L]
    return fam


EXPECTED_FAMILY = {5: (45, 40), 13: (325, 312)}   # version 4, sections 7.2 and 18


def check_family(n_states: int) -> tuple:
    fam, strict = site_family(n_states), site_family(n_states, strict=True)
    if n_states in EXPECTED_FAMILY:
        assert (len(fam), len(strict)) == EXPECTED_FAMILY[n_states], (len(fam), len(strict))
    return fam, strict


# ------------------------------------------------------------ the data

class EvalData:
    """The evaluation sets of `grammar.EVAL_SETS`, as tensors. `scale` < 1
    shrinks every set for a pipeline test (method note, test T6); a scaled
    run is never a registered figure and says so in its output."""

    def __init__(self, scale: float = 1.0):
        self.scale = scale

        def pairs(name):
            n, seed, pool, relaxed = G.EVAL_SETS[name]
            n = max(10, int(round(n * scale)))
            return G.make_pairs(n, seed=seed, pool=pool, collide=relaxed)

        def rd(ps):
            return (M.to_torch(G.batch([p["recipient"] for p in ps]), DEVICE),
                    M.to_torch(G.batch([p["donor"] for p in ps]), DEVICE))

        self.dev_pairs = pairs("dev")
        self.fresh_pairs = pairs("fresh")
        self.relaxed_pairs = pairs("relaxed")
        self.gate_pairs = pairs("gate")
        self.dev = rd(self.dev_pairs)
        self.fresh = rd(self.fresh_pairs)
        self.relaxed = rd(self.relaxed_pairs)
        gate_eps = G.episodes_from_pairs(self.gate_pairs)
        self.gate = M.to_torch(G.batch(gate_eps), DEVICE)
        self.gate_candidates = candidate_ids(gate_eps)
        self.dev_swap = M.to_torch(G.batch(G.named_swap(self.dev_pairs, G.DEV_SWAP_SEED)), DEVICE)
        self.fresh_swap = M.to_torch(G.batch(G.named_swap(self.fresh_pairs, G.FRESH_SWAP_SEED)), DEVICE)
        n = len(self.dev_pairs)
        self.held_out = n - int(0.7 * n)
        self.piece_min = int(np.ceil(MS.FLOOR_SHARE * self.held_out))
        self.gate_min = MS.GATE_MIN_CORRECT if scale == 1.0 else None
        if scale == 1.0:
            assert self.held_out == MS.HELD_OUT and self.piece_min == MS.PIECE_MIN
            assert self.gate["tokens"].shape[0] == MS.GATE_EPISODES


# ------------------------------------------------------------ the gate

@torch.no_grad()
def _accuracy(m, b, lesion=False, chunk=512, with_predictions=False):
    """The rehearsal's `training.accuracy`: each condition separately, never
    combined, argmax over the whole vocabulary."""
    if lesion:
        b = dict(b)
        b["acting"] = torch.zeros_like(b["acting"])
    n = b["tokens"].shape[0]
    hits = np.zeros(2, dtype=np.int64)
    preds = []
    for s in range(0, n, chunk):
        sl = {k: v[s:min(s + chunk, n)] for k, v in b.items()}
        logits = m(sl)
        preds.append(logits.argmax(-1).cpu().numpy())
        for c in (G.OWN, G.OTHER):
            hits[c] += int((logits[:, c].argmax(-1) == sl["targets"][:, c]).sum())
    if with_predictions:
        return int(hits[G.OWN]), int(hits[G.OTHER]), n, np.concatenate(preds)
    return int(hits[G.OWN]), int(hits[G.OTHER]), n


def candidate_ids(episodes: list) -> np.ndarray:
    """Per episode and condition, the vocabulary ids of the four candidate
    answers that remain once "which agent am I" is taken away: the successor
    of each of the four agents' earlier values on the item that condition's
    action names (page 1, RT-237; the rehearsal's
    `lesion_content_check.candidates`)."""
    out = np.zeros((len(episodes), 2, G.N_AGENTS), dtype=np.int64)
    for i, e in enumerate(episodes):
        for c, item in ((G.OWN, e["own_item"]), (G.OTHER, e["other_item"])):
            for a in range(G.N_AGENTS):
                out[i, c, a] = G.VOCAB[G.SLOTS[G.successor(int(e["values"][a, item]))]]
    return out


def candidate_count(pred: np.ndarray, cand: np.ndarray, cond: int) -> int:
    """How many answers in condition `cond` are one of the four candidates."""
    return int((pred[:, cond][:, None] == cand[:, cond, :]).any(axis=1).sum())


def binomial_bar(n: int) -> int:
    """Above one in four at the 0.05 level, one-sided: the smallest count
    whose upper tail under one in four is at most 0.05 (790 of 3,000)."""
    from scipy.stats import binom
    k = int(n / 4)
    while binom.sf(k - 1, n, 0.25) > 0.05:
        k += 1
    return k


def gate(m, arm: str, data: EvalData) -> dict:
    """Section 8.1, and the lesion of section 8.2 computed for every arm."""
    own, oth, n = _accuracy(m, data.gate)
    l_own, l_oth, _, l_pred = _accuracy(m, data.gate, lesion=True, with_predictions=True)
    bar = data.gate_min if data.gate_min is not None else binomial_bar(n)
    line = MS.ownership_free_line(n)
    if n == MS.GATE_EPISODES:
        assert line == MS.OWNERSHIP_FREE_LINE
    row = dict(episodes=n, bar=bar, own_correct=own, other_correct=oth,
               own=own / n, other=oth / n,
               lesioned_own_correct=l_own, lesioned_other_correct=l_oth,
               # page 1 (RT-237): the field the ownership-free line is evaluated on
               lesioned_candidate_own_correct=candidate_count(l_pred, data.gate_candidates, G.OWN),
               lesioned_candidate_other_correct=candidate_count(l_pred, data.gate_candidates, G.OTHER),
               ownership_free_line=line,
               own_clears=own >= bar, other_clears=oth >= bar,
               lesion_collapses_own=l_own < bar)
    row["seed_passes"] = row["own_clears"] and (arm != "F" or row["other_clears"])
    if arm == "M":
        route = m.entangled_route(data.gate)[:, G.OWN].numpy()
        with torch.no_grad():
            pred = torch.cat([m({k: v[s:s + 512] for k, v in data.gate.items()})[:, G.OWN].argmax(-1)
                              for s in range(0, n, 512)])
        hit = (pred == data.gate["targets"][:, G.OWN]).numpy()
        row["own_by_route"] = dict(entangled=float(hit[route].mean()),
                                   separable=float(hit[~route].mean()),
                                   entangled_share=float(route.mean()))
    row["route_in_use"] = route_in_use(m, arm, data.gate)
    return row


def swap_answer(b: dict, shift: int = 1) -> dict:
    """The same episodes with the built-in ownership answer pointing at
    another agent: every agent label in the tally moved on by `shift`, so the
    answer names the next agent round. Text, acting signal and everything
    else unchanged; `assign_agent_at` is read only by the ownership answer."""
    out = dict(b)
    at = b["assign_agent_at"]
    out["assign_agent_at"] = torch.where(at >= 0, (at + shift) % G.N_AGENTS, at)
    return out


@torch.no_grad()
def route_in_use(m, arm: str, b: dict, chunk: int = 512) -> dict:
    """The in-use check (John's ruling of 2026-10-06, option 4; method
    `docs/2026-10-06-sharpness-fix-inuse-check-method.md`, section 2),
    judged by `measure.route_check`. Part A: the mean weight the built answer
    puts, at the own-directed action, on the agent the acting signal fired
    for. Part B, per built route: of the own-directed actions right with the
    true answer, the share no longer right with the answer swapped to another
    agent. Computed for every arm; arm F's is a reference only."""
    n = b["tokens"].shape[0]
    weights, base, swapped = [], [], []
    sw = swap_answer(b)
    for s in range(0, n, chunk):
        sl = {k: v[s:min(s + chunk, n)] for k, v in b.items()}
        ssl = {k: v[s:min(s + chunk, n)] for k, v in sw.items()}
        _, p_own = m._own_vec(sl)
        ap = sl["action_pos"][:, G.OWN]
        rows = torch.arange(ap.shape[0])
        at = sl["assign_agent_at"]
        one = torch.nn.functional.one_hot(at.clamp(min=0), G.N_AGENTS).float() * (at >= 0).float().unsqueeze(-1)
        tally = (one * sl["acting"].float().unsqueeze(-1)).sum(1)
        true_agent = tally.argmax(-1)
        weights.append(p_own[rows, ap, true_agent])
        tgt = sl["targets"][:, G.OWN]
        base.append(m(sl)[:, G.OWN].argmax(-1) == tgt)
        swapped.append(m(ssl)[:, G.OWN].argmax(-1) == tgt)
    base, swapped = torch.cat(base).numpy(), torch.cat(swapped).numpy()
    if arm == "M":
        ent = m.entangled_route(b)[:, G.OWN].numpy()
        masks = {"entangled_items": ent, "separable": ~ent}
    elif arm == "T":
        masks = {"slot": np.ones(n, dtype=bool)}
    else:
        masks = {"entangled": np.ones(n, dtype=bool)}
    routes = {}
    for name, mk in masks.items():
        rt, rs = int(base[mk].sum()), int((base & swapped)[mk].sum())
        routes[name] = dict(actions=int(mk.sum()), right_with_true_answer=rt,
                            still_right_with_swapped_answer=rs,
                            route_use=None if rt == 0 else (rt - rs) / rt)
    rec = dict(sharpness=float(m.own_sharpness),
               sharpness_learned=any(k == "own_sharpness" for k, _ in m.named_parameters()),
               weight_on_true_agent=float(torch.cat(weights).mean()),
               routes=routes, weight_bar=MS.ROUTE_WEIGHT_MIN, use_bar=MS.ROUTE_USE_MIN)
    rec["state"], rec["reasons"] = MS.route_check(rec, arm)
    return rec


# ------------------------------------------------------------ the reads

def read_labels(b: dict, target: str) -> np.ndarray:
    """Which marker word is the model's own (the one registered read), or the
    named agent's (for control 2)."""
    markers = b["agent_marker_tok"].numpy()
    if target == "own":
        agent_at, acting = b["assign_agent_at"], b["acting"]
        idx = torch.argmax(((agent_at >= 0) & (acting == 1)).int(), dim=1)
        who = agent_at[torch.arange(agent_at.shape[0]), idx].numpy()
        return markers[np.arange(len(who)), who]
    named = b["action_who"][:, G.OTHER].numpy()
    return markers[np.arange(len(named)), named]


def action_states(m, b, cond):
    with torch.no_grad():
        _, states = m(b, capture=True)
    ap = b["action_pos"][:, cond]
    rows = torch.arange(b["tokens"].shape[0])
    return [st[rows, ap].numpy() for st in states], states


def _fit(h, y):
    n_tr = int(0.7 * len(y))
    return LogisticRegression(max_iter=3000, C=1.0).fit(h[:n_tr], y[:n_tr]), n_tr


def correct_count(h, y) -> int:
    """Held-out correct of a fresh read on features h: the rehearsal's
    `rerun_controls.correct_count`."""
    if h.ndim == 1:
        h = h[:, None]
    clf, n_tr = _fit(h, y)
    return int(round(clf.score(h[n_tr:], y[n_tr:]) * (len(y) - n_tr)))


def fit_reads(m, dev_recip) -> dict:
    """The one fit, per running state, on development episodes only: the
    ownership read at the own-directed action, and the named agent's read at
    the named-other action (control 2)."""
    out = {}
    for target, cond in (("own", G.OWN), ("named", G.OTHER)):
        hs, _ = action_states(m, dev_recip, cond)
        y = read_labels(dev_recip, target)
        out[target] = {l: _fit(h, y)[0].coef_.astype(np.float64) for l, h in enumerate(hs)}
    return out


def save_reads(path, reads):
    np.savez(path, **{f"{t}|{l}": c for t, d in reads.items() for l, c in d.items()})


def load_reads(path) -> dict:
    z = np.load(path)
    out = {"own": {}, "named": {}}
    for k in z.files:
        t, l = k.split("|")
        if t in out:
            out[t][int(l)] = z[k]
    return out


def accuracies(m, recip, coefs, target, cond) -> dict:
    """Per running state: the whole read's held-out count, and each size's
    piece count (the rehearsal's `rerun_controls.accuracies`)."""
    hs, _ = action_states(m, recip, cond)
    y = read_labels(recip, target)
    out = {}
    for l, h in enumerate(hs):
        out[l] = dict(whole=correct_count(h, y),
                      piece={r: correct_count(h @ X.basis_for(coefs[l], r).numpy(), y) for r in RANKS})
    return out


def null(m, recip, seed: int, shuffles: int) -> dict:
    """The label-permutation null for the whole read, every state: a reference
    beside the floor, not the bar (the rehearsal's `rerun_v3.stage_null`)."""
    hs, _ = action_states(m, recip, G.OWN)
    y = read_labels(recip, "own")
    n_tr = int(0.7 * len(y))
    out = {}
    for l, h in enumerate(hs):
        rng = np.random.default_rng([20260926, seed, l])
        sc = []
        for _ in range(shuffles):
            yy = rng.permutation(y)
            clf = LogisticRegression(max_iter=3000, C=1.0).fit(h[:n_tr], yy[:n_tr])
            sc.append(clf.score(h[n_tr:], yy[n_tr:]) * (len(y) - n_tr))
        sc = np.array(sc)
        out[l] = dict(p95=float(np.percentile(sc, 95)), p99=float(np.percentile(sc, 99)),
                      max=float(sc.max()), mean=float(sc.mean()), shuffles=shuffles)
    return out


# ------------------------------------------------------------ nomination

def hits(out, target, cond) -> np.ndarray:
    return (X.predictions(out, cond) == target).numpy().astype(np.int8)


def run(m, recip, d_states, sites, mask, basis):
    return X.transplanted_logits(m, recip, d_states, sites, mask, basis)


def grid(m, recip, donor, coefs, cond, family):
    """Every site set of the family at every size, on development episodes."""
    d_states = X.capture(m, donor)
    d_tgt = donor["targets"][:, cond]
    with torch.no_grad():
        clean = m(recip)
    u = float(hits(clean, d_tgt, cond).mean())
    acc = float(hits(clean, recip["targets"][:, cond], cond).mean())
    rows = []
    for L, P in family:
        sites = X.Sites(layers=tuple(L), positions=P)
        mask = X.anchored_mask(recip, P, cond)
        whole = float(hits(run(m, recip, d_states, sites, mask, None), d_tgt, cond).mean())
        fl = MS.floor_check(whole, u, acc)
        for r in RANKS:
            basis = {l: X.basis_for(coefs[l], r) for l in L}
            own = float(hits(run(m, recip, d_states, sites, mask, basis), d_tgt, cond).mean())
            rows.append(dict(layers=list(L), positions=P, rank=r, accuracy_whole=whole,
                             accuracy_ownership_only=own, floor=fl))
    return dict(untouched=u, arm_accuracy=acc, grid=rows)


def pick(rows, fits, family, piece_min, require_piece=True):
    """The rule (the rehearsal's `rerun_controls.pick`): among site sets whose
    whole-state transplant clears the floor, per position set the smallest
    layer set; among those, only sizes whose piece reaches the fit floor; then
    the highest ownership-only share, ties to the smaller size and the earlier
    position set."""
    fam = {(tuple(L), P) for L, P in family}
    pos_index = {P: i for i, P in enumerate(POS)}
    clearing = [g for g in rows if g["floor"]["clears"] and (tuple(g["layers"]), g["positions"]) in fam]
    if not clearing:
        return None, "no site set clears the whole-state floor", []
    smallest = {}
    for g in clearing:
        key = (len(g["layers"]), g["layers"])
        if g["positions"] not in smallest or key < smallest[g["positions"]]:
            smallest[g["positions"]] = key
    cands = [dict(g, piece_correct=min(fits[l]["piece"][g["rank"]] for l in g["layers"]),
                  whole_read_correct=min(fits[l]["whole"] for l in g["layers"]))
             for g in clearing if (len(g["layers"]), g["layers"]) == smallest[g["positions"]]]
    ok = [g for g in cands if g["piece_correct"] >= piece_min] if require_piece else cands
    if not ok:
        return None, "read failed its floor: no size's piece reaches four fifths", cands
    best = min(ok, key=lambda g: (-g["accuracy_ownership_only"], g["rank"], pos_index[g["positions"]]))
    return best, "nominated", cands


def pick_sensitivity(rows, fits, family, piece_min):
    """The repairs-style sensitivity row for the whole-state layer set: the
    same rule without "the smallest layer set", so any clearing layer set may
    win on its ownership-only share. Reported beside, never instead."""
    pos_index = {P: i for i, P in enumerate(POS)}
    fam = {(tuple(L), P) for L, P in family}
    ok = []
    for g in rows:
        if g["floor"]["clears"] and (tuple(g["layers"]), g["positions"]) in fam:
            pc = min(fits[l]["piece"][g["rank"]] for l in g["layers"])
            if pc >= piece_min:
                ok.append(dict(g, piece_correct=pc,
                               whole_read_correct=min(fits[l]["whole"] for l in g["layers"])))
    if not ok:
        return None
    return min(ok, key=lambda g: (-g["accuracy_ownership_only"], len(g["layers"]), g["rank"],
                                  pos_index[g["positions"]], g["layers"]))


def spec_of(g):
    return None if g is None else dict(layers=list(g["layers"]), positions=g["positions"],
                                       rank=g["rank"], piece_correct=g["piece_correct"],
                                       whole_read_correct=g["whole_read_correct"])


def other_positions(positions):
    """The positions other than the action that a piece's accuracy is also
    taken at (the rehearsal's `short_prestated_run.other_positions`)."""
    if positions == "action":
        return []
    if positions == "action+ans":
        return [("1 before the action", "action", -1)]
    if positions == "action+3":
        return [(f"{k} before the action", "action", -k) for k in (1, 2, 3)]
    if positions == "post-identity":
        return ([(f"first own turn, token {k + 1} of {OWN_TURN_LEN}", "first", k) for k in range(OWN_TURN_LEN)]
                + [(f"{k} before the action", "action", -k) for k in range(ACTION_TURN_BEFORE, 0, -1)])
    raise ValueError(positions)


def piece_elsewhere(m, dev, spec, coefs) -> dict:
    """The chosen piece's count at the other positions of its site, both ways:
    each position, and the average over them (ruled 2026-10-03; reported, no
    pass line). The rehearsal's `short_prestated_run.part_b`."""
    y = read_labels(dev, "own")
    B = dev["tokens"].shape[0]
    rows = torch.arange(B)
    ap = dev["action_pos"][:, G.OWN]
    fo = torch.argmax(dev["acting"], dim=1)
    with torch.no_grad():
        _, states = m(dev, capture=True)
    L = spec["layers"]
    Q = {l: X.basis_for(coefs[l], spec["rank"]).numpy() for l in L}

    def counts(feature):
        per = [(correct_count(feature(l), y), correct_count(feature(l) @ Q[l], y)) for l in L]
        return dict(whole=min(p[0] for p in per), piece=min(p[1] for p in per))

    at_action = counts(lambda l: states[l][rows, ap].numpy())
    entries = []
    for name, anchor, off in other_positions(spec["positions"]):
        where = (ap if anchor == "action" else fo) + off
        entries.append(dict(position=name, **counts(lambda l: states[l][rows, where].numpy())))
    span_mean = None
    if spec["positions"] != "action":
        mask = X.position_mask(dev, spec["positions"])
        mask[rows, ap] = False
        w = mask.float()
        span_mean = counts(lambda l: ((states[l] * w[..., None]).sum(1) / w.sum(1, keepdim=True)).numpy())
    return dict(at_the_action_position=at_action, other_positions=entries,
                mean_over_the_other_positions=span_mean)


